import { act, renderHook } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { ALERT_DRAIN_MS, ALERT_POLL_MS, useNotificationAlerts } from './useNotificationAlerts'
import { alertPage, liveAlert } from '../test/alertFixtures'
import { jsonResponse } from '../test/durableFixtures'

const origin = 'http://127.0.0.1:8082'
const flush = async () => { await act(async () => { await Promise.resolve() }) }
const advance = async (ms: number) => { await act(async () => { await vi.advanceTimersByTimeAsync(ms) }) }
describe('Polling incremental aislado del marcador', () => {
  beforeEach(() => vi.useFakeTimers())
  afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals() })
  it('carga la primera página y luego usa su cursor', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'first')))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2)], 'second')))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    expect(result.current.status).toBe('loading')
    await flush(); expect(result.current.items).toHaveLength(1)
    await advance(ALERT_POLL_MS)
    expect(new URL(fetcher.mock.calls[1][0]).searchParams.get('after')).toBe('first')
    expect(result.current.items.map(item => item.source_event_id)).toEqual(['event-1', 'event-2'])
  })
  it('drena has_more con pausas y deduplica páginas', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'a', true)))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(), liveAlert(2)], 'b')))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); expect(fetcher).toHaveBeenCalledTimes(1)
    await advance(ALERT_DRAIN_MS - 1); expect(fetcher).toHaveBeenCalledTimes(1)
    await advance(1); expect(fetcher).toHaveBeenCalledTimes(2); expect(result.current.items).toHaveLength(2)
  })
  it('cancela el partido anterior y descarta su respuesta tardía', async () => {
    let resolveOld!: (response: Response) => void
    const fetcher = vi.fn().mockImplementationOnce(() => new Promise<Response>(resolve => { resolveOld = resolve }))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2, { match_id: 'match-002' })], 'new')))
    vi.stubGlobal('fetch', fetcher)
    const { result, rerender } = renderHook(({ id }) => useNotificationAlerts(id, origin), { initialProps: { id: 'match-001' } })
    const oldSignal = fetcher.mock.calls[0][1].signal as AbortSignal
    rerender({ id: 'match-002' }); expect(oldSignal.aborted).toBe(true)
    await flush()
    await act(async () => resolveOld(jsonResponse(alertPage([liveAlert()], 'old'))))
    expect(result.current.items.map(item => item.match_id)).toEqual(['match-002'])
  })
  it('no superpone peticiones ni consulta tras desmontar', async () => {
    let resolve!: (response: Response) => void
    const fetcher = vi.fn(() => new Promise<Response>(done => { resolve = done }))
    vi.stubGlobal('fetch', fetcher)
    const { unmount } = renderHook(() => useNotificationAlerts('match-001', origin))
    await advance(ALERT_POLL_MS); expect(fetcher).toHaveBeenCalledTimes(1)
    const signal = (fetcher.mock.calls[0] as unknown as [string, RequestInit])[1].signal!
    unmount(); expect(signal.aborted).toBe(true)
    expect(vi.getTimerCount()).toBe(0)
    await act(async () => resolve(jsonResponse(alertPage())))
    await advance(60000); expect(fetcher).toHaveBeenCalledTimes(1)
  })
  it('un 409 incremental recupera la página inicial y reemplaza la época anterior', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'old')))
      .mockResolvedValueOnce(jsonResponse({}, 409)).mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(9)], 'new')))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_POLL_MS)
    expect(result.current.items).toHaveLength(1)
    await advance(ALERT_DRAIN_MS)
    expect(new URL(fetcher.mock.calls[2][0]).searchParams.has('after')).toBe(false)
    expect(result.current.items.map(item => item.source_event_id)).toEqual(['event-9'])
  })
  it('detiene un 409 repetido en vez de entrar en un bucle', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([], 'a')))
      .mockResolvedValueOnce(jsonResponse({}, 409)).mockResolvedValueOnce(jsonResponse({}, 409))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_POLL_MS); await advance(ALERT_DRAIN_MS)
    expect(result.current.status).toBe('error')
    await advance(60000); expect(fetcher).toHaveBeenCalledTimes(3)
  })
  it('limita restablecimientos de cursor cercanos y el reintento manual carga desde el inicio', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'a')))
      .mockResolvedValueOnce(jsonResponse({}, 409)).mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2)], 'b')))
      .mockResolvedValueOnce(jsonResponse({}, 409)).mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(3)], 'c')))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_POLL_MS); await advance(ALERT_DRAIN_MS); await advance(ALERT_POLL_MS)
    expect(result.current.status).toBe('error'); expect(fetcher).toHaveBeenCalledTimes(4)
    act(() => result.current.retry()); await flush()
    expect(new URL(fetcher.mock.calls[4][0]).searchParams.has('after')).toBe(false)
    expect(result.current.items.map(item => item.source_event_id)).toEqual(['event-3'])
  })
  it('conserva las alertas ante 503 y reintenta con el último cursor confirmado', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'confirmed')))
      .mockResolvedValueOnce(jsonResponse({}, 503)).mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2)], 'next')))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_POLL_MS)
    expect(result.current.status).toBe('error'); expect(result.current.items).toHaveLength(1)
    await advance(60000); expect(fetcher).toHaveBeenCalledTimes(2)
    act(() => result.current.retry()); await flush()
    expect(new URL(fetcher.mock.calls[2][0]).searchParams.get('after')).toBe('confirmed')
    expect(result.current.items).toHaveLength(2)
  })
  it('muestra fallo de red y permite reintento manual', async () => {
    const fetcher = vi.fn().mockRejectedValueOnce(new TypeError('Failed to fetch')).mockResolvedValueOnce(jsonResponse(alertPage()))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); expect(result.current.error).toContain('No se pudo conectar')
    act(() => result.current.retry()); await flush(); expect(result.current.status).toBe('ready')
  })
  it('rechaza un cursor sin avance y conserva el estado válido', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'same', true)))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2)], 'same', true)))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_DRAIN_MS)
    expect(result.current.status).toBe('error'); expect(result.current.items).toHaveLength(1)
    await advance(60000); expect(fetcher).toHaveBeenCalledTimes(2)
  })
  it('el timeout aborta una consulta bloqueada y no activa reintentos automáticos', async () => {
    const fetcher = vi.fn((_input: string, options: RequestInit) => new Promise<Response>((_resolve, reject) => {
      options.signal?.addEventListener('abort', () => reject(new DOMException('Aborted', 'AbortError')))
    }))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await advance(10000)
    expect(result.current.status).toBe('error'); expect(result.current.error).toContain('tiempo de espera')
    await advance(60000); expect(fetcher).toHaveBeenCalledTimes(1)
  })
  it('configuración ausente o inválida y falta de selección no abren conexiones', async () => {
    const fetcher = vi.fn(); vi.stubGlobal('fetch', fetcher)
    const first = renderHook(() => useNotificationAlerts('match-001', undefined))
    const second = renderHook(() => useNotificationAlerts('match-001', 'http://user:pass@localhost'))
    const third = renderHook(() => useNotificationAlerts(null, origin))
    await advance(60000)
    expect(first.result.current.status).toBe('disabled'); expect(second.result.current.error).toContain('Configura')
    expect(third.result.current.status).toBe('disabled'); expect(fetcher).not.toHaveBeenCalled()
  })
  it('avanza el cursor de una página vacía sin perder las alertas anteriores', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'a')))
      .mockResolvedValueOnce(jsonResponse(alertPage([], 'b')))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2)], 'c')))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_POLL_MS); await advance(ALERT_POLL_MS)
    expect(new URL(fetcher.mock.calls[2][0]).searchParams.get('after')).toBe('b')
    expect(result.current.items.map(item => item.source_event_id)).toEqual(['event-1', 'event-2'])
  })
  it('drena varias páginas en orden, deduplica UUID sin distinguir mayúsculas y detecta ciclos', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'a', true)))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(1, { alert_id: liveAlert().alert_id.toUpperCase() }), liveAlert(2)], 'b', true)))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(3)], 'c', true)))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(4)], 'a', true)))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_DRAIN_MS); await advance(ALERT_DRAIN_MS)
    expect(result.current.items.map(item => item.source_event_id)).toEqual(['event-1', 'event-2', 'event-3'])
    await advance(ALERT_DRAIN_MS)
    expect(result.current.status).toBe('error'); expect(result.current.items).toHaveLength(3)
    await advance(60000); expect(fetcher).toHaveBeenCalledTimes(4)
  })
  it('cambiar de origen aborta la consulta y descarta su respuesta tardía', async () => {
    let resolveOld!: (response: Response) => void
    const fetcher = vi.fn().mockImplementationOnce(() => new Promise<Response>(resolve => { resolveOld = resolve }))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2)], 'new')))
    vi.stubGlobal('fetch', fetcher)
    const { result, rerender } = renderHook(({ server }) => useNotificationAlerts('match-001', server), { initialProps: { server: origin } })
    const oldSignal = fetcher.mock.calls[0][1].signal as AbortSignal
    rerender({ server: 'http://127.0.0.1:9082' }); await flush()
    expect(oldSignal.aborted).toBe(true)
    await act(async () => resolveOld(jsonResponse(alertPage([liveAlert()], 'old'))))
    expect(result.current.items.map(item => item.source_event_id)).toEqual(['event-2'])
    expect(new URL(fetcher.mock.calls[1][0]).searchParams.has('after')).toBe(false)
  })
  it('un cambio rápido A-B-A ignora respuestas antiguas incluso del mismo partido', async () => {
    const pending: ((response: Response) => void)[] = []
    const fetcher = vi.fn((_input: string, _options: RequestInit) => new Promise<Response>(resolve => pending.push(resolve)))
    vi.stubGlobal('fetch', fetcher)
    const { result, rerender } = renderHook(({ id }) => useNotificationAlerts(id, origin), { initialProps: { id: 'match-001' } })
    rerender({ id: 'match-002' }); rerender({ id: 'match-001' })
    await act(async () => pending[2](jsonResponse(alertPage([liveAlert(3)], 'current'))))
    await act(async () => pending[0](jsonResponse(alertPage([liveAlert()], 'obsolete'))))
    await act(async () => pending[1](jsonResponse(alertPage([liveAlert(2, { match_id: 'match-002' })], 'other'))))
    expect(result.current.items.map(item => item.source_event_id)).toEqual(['event-3'])
    await advance(ALERT_POLL_MS)
    expect(new URL(fetcher.mock.calls[3][0]).searchParams.get('after')).toBe('current')
  })
  it('rechaza datos malformados sin avanzar cursor y recupera tras reintento manual', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'confirmed')))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2, { created_at: '2026-02-30T12:00:00Z' })], 'invalid')))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2)], 'next')))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_POLL_MS)
    expect(result.current.status).toBe('error'); expect(result.current.items).toHaveLength(1)
    act(() => result.current.retry()); await flush()
    expect(new URL(fetcher.mock.calls[2][0]).searchParams.get('after')).toBe('confirmed')
    expect(result.current.items).toHaveLength(2)
  })
  it('un 409 durante drenaje recupera una ventana nueva sin mezclar épocas', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'a', true)))
      .mockResolvedValueOnce(jsonResponse({}, 409)).mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(8)], 'new')))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_DRAIN_MS); await advance(ALERT_DRAIN_MS)
    expect(new URL(fetcher.mock.calls[2][0]).searchParams.has('after')).toBe(false)
    expect(result.current.items.map(item => item.source_event_id)).toEqual(['event-8'])
  })
  it('un fallo temporal de red conserva el checkpoint al reintentar', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'confirmed')))
      .mockRejectedValueOnce(new TypeError('private diagnostic')).mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2)], 'next')))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_POLL_MS)
    expect(result.current.error).not.toContain('private diagnostic')
    act(() => result.current.retry()); await flush()
    expect(new URL(fetcher.mock.calls[2][0]).searchParams.get('after')).toBe('confirmed')
    expect(result.current.items).toHaveLength(2)
  })
  it('un 400 detiene polling y el reintento manual reinicia la consulta', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([liveAlert()], 'bad-cursor')))
      .mockResolvedValueOnce(jsonResponse({}, 400)).mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2)], 'fresh')))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_POLL_MS); await advance(60000)
    expect(result.current.status).toBe('error'); expect(fetcher).toHaveBeenCalledTimes(2)
    act(() => result.current.retry()); await flush()
    expect(new URL(fetcher.mock.calls[2][0]).searchParams.has('after')).toBe(false)
    expect(result.current.items.map(item => item.source_event_id)).toEqual(['event-2'])
  })
  it('desactivar configuración limpia recursos e ignora la respuesta pendiente', async () => {
    let resolveOld!: (response: Response) => void
    const fetcher = vi.fn().mockImplementationOnce(() => new Promise<Response>(resolve => { resolveOld = resolve }))
      .mockResolvedValueOnce(jsonResponse(alertPage([liveAlert(2)], 'fresh')))
    vi.stubGlobal('fetch', fetcher)
    const { result, rerender } = renderHook(({ server }: { server: string | undefined }) => useNotificationAlerts('match-001', server), { initialProps: { server: origin as string | undefined } })
    const oldSignal = fetcher.mock.calls[0][1].signal as AbortSignal
    rerender({ server: undefined })
    expect(oldSignal.aborted).toBe(true); expect(vi.getTimerCount()).toBe(0)
    await act(async () => resolveOld(jsonResponse(alertPage([liveAlert()], 'obsolete'))))
    await advance(60000)
    expect(result.current.status).toBe('disabled'); expect(result.current.items).toHaveLength(0)
    expect(fetcher).toHaveBeenCalledTimes(1)
    rerender({ server: origin }); await flush()
    expect(new URL(fetcher.mock.calls[1][0]).searchParams.has('after')).toBe(false)
    expect(result.current.items.map(item => item.source_event_id)).toEqual(['event-2'])
  })
  it('conserva una alerta atrasada según el cursor recibido sin reordenar por fecha ni recalcular el estado VAR', async () => {
    const latest = liveAlert(1, { alert_type: 'VAR_CHECK', reference_event_id: 'goal-1', var_status: 'IN_PROGRESS' })
    const delayed = liveAlert(2, { alert_type: 'GOAL_ANNULLED', reference_event_id: 'goal-1', var_status: 'IN_PROGRESS',
      source_updated_at: '2026-11-15T15:00:00Z', created_at: '2026-11-15T15:00:01Z', home_score: 0 })
    const fetcher = vi.fn().mockResolvedValueOnce(jsonResponse(alertPage([latest], 'committed-1')))
      .mockResolvedValueOnce(jsonResponse(alertPage([latest, delayed], 'committed-2')))
    vi.stubGlobal('fetch', fetcher)
    const { result } = renderHook(() => useNotificationAlerts('match-001', origin))
    await flush(); await advance(ALERT_POLL_MS)
    expect(result.current.items).toEqual([latest, delayed])
    expect(new URL(fetcher.mock.calls[1][0]).searchParams.get('after')).toBe('committed-1')
    expect(result.current.items[1].var_status).toBe('IN_PROGRESS')
    expect(result.current.items[1].home_score).toBe(0)
  })
})
